using RefractionStudio.Analysis.Picking;
using RefractionStudio.Core;
using RefractionStudio.Core.Import;
using RefractionStudio.Core.Session;
using RefractionStudio.Domain;
using RefractionStudio.Persistence;

namespace RefractionStudio.Synthetics;

/// <summary>Progress of sample-project generation.</summary>
public sealed record SampleProgress(string Stage, double Fraction);

/// <summary>
/// Builds the distributed sample project from synthetic data generated here (no third-party or
/// competitor data). The earth model, acquisition and every processing decision are documented in the
/// project description and history. It demonstrates P and SH lines, topography, reference-geophone
/// trigger correction, filtering, automatic and reviewed picks, a dead and a reversed channel, layered
/// interpretation, tomography, Vs30 and engineering properties.
/// </summary>
public static class SampleProjectBuilder
{
    public const int Channels = 48;
    public const double Spacing = 3.0;
    public static readonly double[] Shots = [-36, -1.5, 34.5, 70.5, 106.5, 142.5, 177];
    public static readonly double[] TriggerErrors = [0, 0.0025, 0, -0.0015, 0, 0, 0.002];

    /// <summary>Ground surface of the sample site.</summary>
    public static Topography SiteTopography { get; } = Topography.Create(
        Enumerable.Range(0, 23).Select(i => -40.0 + i * 10).Select(x => new TopographyPoint(x, 100 + 3 * Math.Sin(x / 45) + 0.01 * x)));

    /// <summary>Depth of the soil / weathered-layer boundary.</summary>
    public static double Interface1(double x) => 3.0 + 0.6 * Math.Sin(x / 20);

    /// <summary>Depth of the top of bedrock.</summary>
    public static double Interface2(double x) => 13.0 + 2.5 * Math.Sin(x / 32) - 0.01 * x;

    public static double Vp(double x, double d) => d < Interface1(x) ? 450 : d < Interface2(x) ? 1650 : 3000 + 40 * (d - Interface2(x));

    public static double Vs(double x, double d) => d < Interface1(x) ? 210 : d < Interface2(x) ? 420 : 1250 + 25 * (d - Interface2(x));

    /// <summary>The synthetic P and SH surveys of the sample (deterministic; includes the true travel times).</summary>
    public static (SyntheticSurvey P, SyntheticSurvey SH) GenerateSurveys()
    {
        var pModel = new GridSyntheticModel(Vp, SiteTopography, Shots.Min() - 2, Shots.Max() + 2, 45, 1.0, "Sample site P-wave model");
        var pSurvey = SurveyGenerator.Generate(pModel, new SyntheticSurveyOptions(Channels, Spacing, 0, Shots, 0.000125, 2048, -0.005, 70, NoiseLevel,
            TriggerErrors, DeadChannels: null, ReversedChannels: [17], WaveType.P, SiteTopography, Seed: 2026, ReferenceChannel: true, FormatCode: 2));
        var sModel = new GridSyntheticModel(Vs, SiteTopography, Shots.Min() - 2, Shots.Max() + 2, 45, 1.0, "Sample site SH-wave model");
        var sSurvey = SurveyGenerator.Generate(sModel, new SyntheticSurveyOptions(Channels, Spacing, 0, Shots, 0.00025, 2048, -0.01, 35, NoiseLevel,
            null, null, null, WaveType.SH, SiteTopography, Seed: 2027, ReferenceChannel: false, FormatCode: 2));
        return (pSurvey, sSurvey);
    }

    /// <summary>Noise level of the sample records.</summary>
    public const double NoiseLevel = 0.04;

    public static async Task<ProjectWorkspace> BuildAsync(string workDirectory, WorkspaceOptions options, IProgress<SampleProgress>? progress = null, CancellationToken ct = default)
    {
        Directory.CreateDirectory(workDirectory);
        var ws = new ProjectWorkspace(options);
        ws.NewProject("Sample Site — Seismic Refraction (synthetic)");
        ws.Session!.Execute(Edits.SetMetadata(ws.State.Metadata with
        {
            ProjectNumber = "QL-SAMPLE-001",
            Client = "Demonstration Client",
            SiteName = "Sample Site",
            SiteAddress = "Synthetic dataset — not a real location",
            Description = "Synthetic demonstration survey generated by Refraction Studio. Earth model: soil (Vp 450 / Vs 210 m/s) over saturated weathered layer " +
                          "(Vp 1650 / Vs 420 m/s) over bedrock (Vp 3000 / Vs 1250 m/s increasing with depth); undulating interfaces and topography. " +
                          "Use it to explore the workflow; it has no engineering significance.",
            SurveyDate = new DateOnly(2026, 10, 1),
            FieldCrew = "Synthetic",
            Instrument = "48-channel seismograph (simulated), 0.125 ms sampling",
            Geophones = "48 × vertical (P) and 48 × horizontal transverse (SH), 3 m spacing",
            Source = "Sledgehammer on plate (P); horizontal shear beam, left and right impacts (SH)",
        }));

        var length = (Channels - 1) * Spacing;
        progress?.Report(new SampleProgress("Computing travel times and waveforms", 0.05));
        var (pSurvey, sSurvey) = GenerateSurveys();
        ct.ThrowIfCancellationRequested();

        var pDir = Path.Combine(workDirectory, "P");
        var sDir = Path.Combine(workDirectory, "SH");
        var pFiles = pSurvey.WriteTo(pDir);
        var sFiles = sSurvey.WriteTo(sDir);
        // One dead trace in a field file (as delivered by an instrument), shown in QC.
        KillChannel(pFiles[2], 30);

        var profile = new SpreadProfile(Guid.NewGuid(), "Sample 48-ch + shot geophone", null, Channels + 1, Spacing, ChannelDirection.Increasing,
            [.. Enumerable.Range(1, Channels).Select(c => new ChannelAssignment(c, ChannelRole.Receiver)), new ChannelAssignment(Channels + 1, ChannelRole.Reference)]);

        progress?.Report(new SampleProgress("Importing P-wave records", 0.45));
        var (pInspected, _, _) = await ws.InspectAsync(pFiles, ct: ct).ConfigureAwait(false);
        var pPlan = ws.Import(pInspected, new ImportOptions(null, "Line 1 — P", WaveType.P, profile, Spacing, GatherGrouping.Separate,
            new HashSet<string>(), new HashSet<(string, int)>()));
        var pLine = pPlan.Line;

        progress?.Report(new SampleProgress("Importing SH-wave records", 0.5));
        var (sInspected, _, _) = await ws.InspectAsync(sFiles, ct: ct).ConfigureAwait(false);
        var sPlan = ws.Import(sInspected, new ImportOptions(null, "Line 1 — SH", WaveType.SH, null, Spacing, GatherGrouping.ShOppositePairs,
            new HashSet<string>(), new HashSet<(string, int)>()));
        var sLine = sPlan.Line;

        // Surveyed ground profile (covers the off-end shots, which the receiver headers do not).
        var session = ws.Session!;
        session.Execute(Edits.SetTopography(pLine, SiteTopography));
        session.Execute(Edits.SetTopography(sLine, SiteTopography));

        // Processing.
        session.Execute(Edits.SetPipeline(pLine, new ProcessingPipeline([
            new RemoveMeanStep(StepId.New(), true),
            new HighPassStep(StepId.New(), true, 15, 2, false)]), "P processing: demean, causal high-pass 15 Hz (suppresses surface waves, preserves onset times)"));
        session.Execute(Edits.SetPipeline(sLine, new ProcessingPipeline([
            new RemoveMeanStep(StepId.New(), true),
            new HighPassStep(StepId.New(), true, 6, 2, false)]), "SH processing: demean, causal high-pass 6 Hz (suppresses surface waves, preserves onset times)"));

        // Trigger correction from the shot geophone.
        session.Execute(Edits.SetShotTimeSettings(pLine, new ShotTimeSettings(ShotTimeMethod.ReferenceGeophone)));
        ws.AutoPickReferences(pLine, new PickerSettings());

        progress?.Report(new SampleProgress("Picking first breaks", 0.55));
        await ws.AutoPickAsync(pLine, new PickerSettings(PickerAlgorithm.Aic, MinApparentVelocity: 200), ct: ct).ConfigureAwait(false);
        await ws.AutoPickAsync(sLine, new PickerSettings(PickerAlgorithm.ShPolarityDivergence, ShortWindow: 0.004, LongWindow: 0.04, MinApparentVelocity: 100), ct: ct).ConfigureAwait(false);
        foreach (var line in new[] { pLine, sLine })
        {
            var picks = ws.State.Interpretation(line).Picks.Where(p => p.Value.Confidence?.Level is ConfidenceLevel.High).Select(p => p.Key).ToList();
            session.Execute(Edits.AcceptPicks(line, picks));
            var observations = Analysis.TravelTimes.ObservationBuilder.Build(ws.State, line);
            session.Execute(Edits.SetSegments(line, new Analysis.TravelTimes.SegmentAssigner().Suggest(observations, 3), "Suggest crossovers for 3 layers"));
            var gathers = ws.State.Survey.Line(line)!.Gathers;
            session.Execute(Edits.SetLayeredSettings(line, new LayeredSettings(LayeredMethod.DelayTime,
                gathers.OrderBy(g => g.ShotX).First(g => g.ShotX > -10).Id, gathers.OrderBy(g => g.ShotX).Last(g => g.ShotX < length + 10).Id)));
        }

        // Review, as an interpreter would: picks that quality control marks as likely problems against
        // their refractor segment are excluded (kept, visible and audited), with the reason recorded.
        var review = ws.Analyze(ct);
        foreach (var line in new[] { pLine, sLine })
        {
            var suspect = review.Qc.Flags.Where(f => f.Line == line && f.Code == "segment-residual" && f.Level == Analysis.Quality.QcLevel.Problem && f.Key is not null)
                .Select(f => f.Key!.Value).Distinct().ToList();
            if (suspect.Count == 0) continue;
            using (session.BeginGesture($"Exclude {suspect.Count} inconsistent pick(s) after review"))
            {
                foreach (var key in suspect)
                {
                    session.Execute(Edits.SetPickIncluded(line, key, false));
                    session.Execute(Edits.SetPickComment(line, key, "Excluded after review: inconsistent with the refractor segment (quality control)."));
                }
            }
        }

        progress?.Report(new SampleProgress("Running P-wave tomography", 0.65));
        var tomography = new TomographySettings(CellWidth: 1.5, CellHeight: 1.5, MaxDepth: 40, MaxIterations: 20, Smoothing: 20, SecondaryNodes: 4);
        await ws.RunTomographyAsync(pLine, tomography, ct: ct).ConfigureAwait(false);
        progress?.Report(new SampleProgress("Running SH-wave tomography", 0.8));
        await ws.RunTomographyAsync(sLine, tomography, ct: ct).ConfigureAwait(false);

        // Engineering settings.
        session.Execute(Edits.SetEngineeringSettings(new EngineeringSettings(pLine, sLine, VelocityModelSource.Tomography, [30, 70.5, 110], 1.0)));
        session.Execute(Edits.SetVs30Settings(new Vs30Settings([30, 70.5, 110], 30, false, [new DepthInterval(0, 10)])));
        session.Execute(Edits.SetDensityModel(new DensityModel(DensitySource.Measured,
            [new DensityInterval(0, 3, 1750, "Assumed for demonstration"), new DensityInterval(3, 14, 1950, "Assumed for demonstration"), new DensityInterval(14, 60, 2400, "Assumed for demonstration")],
            null, "Densities are illustrative values, not measurements.")));
        session.Execute(Edits.SetReport(ws.State.Report with
        {
            Branding = new CompanyBranding("QuakeLogic Inc.", "Demonstration address", null, "info@quakelogic.net", "https://www.quakelogic.net", "Sample report — synthetic data",
                "Demonstration Engineer", null),
            Title = "Seismic Refraction Survey — Sample Site",
            Subtitle = "Synthetic demonstration dataset",
            ReportNumber = "QL-SAMPLE-001-R0",
            PreparedBy = "Refraction Studio sample generator",
            ProcessingNotes = "Shot times corrected from the shot geophone (channel 49), picked on the unfiltered trace. Causal high-pass filtering " +
                              "before automatic picking: zero-phase filters would place energy ahead of the true first break and causal low-pass filters delay it. " +
                              "High-confidence automatic picks were accepted. Picks that quality control marked as inconsistent with their refractor segment " +
                              "were excluded after review (they remain in the pick tables); the other automatic picks are left for review to demonstrate quality control.",
            Conclusions = "This report was generated from synthetic data to demonstrate the software. It contains no engineering conclusions.",
        }));
        progress?.Report(new SampleProgress("Done", 1.0));
        return ws;
    }

    private static void KillChannel(string seg2Path, int channel)
    {
        var bytes = File.ReadAllBytes(seg2Path);
        var file = Formats.Seg2Reader.Parse(bytes, Path.GetFileName(seg2Path), includeSamples: true);
        var traces = file.Records[0].Traces.Select(t => new Formats.Seg2TraceToWrite(t.Header.Keywords,
            t.Header.Channel == channel ? new double[t.Samples.Length] : RescaleBack(t))).ToList();
        File.WriteAllBytes(seg2Path, Formats.Seg2Writer.Write(file.Records[0].Keywords, traces, 2));
    }

    // Samples were descaled on reading; restore the stored integers so that DESCALING_FACTOR stays valid.
    private static double[] RescaleBack(Formats.DecodedTrace t)
    {
        var f = t.Header.Keywords.TryGetValue("DESCALING_FACTOR", out var s) && double.TryParse(s, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out var d) && d != 0 ? d : 1;
        return [.. t.Samples.Select(v => Math.Round(v / f))];
    }
}
